"""Build the RFC 5322 message for a send: headers, simulated authentication trace, body, attachment.

Header simulation
-----------------
Real SPF/DKIM/DMARC results are produced by the *receiving* MTA after checking DNS. The demo
receiver does not verify anything, so for the demo the ``Authentication-Results`` header is
written here, on the message the demo tool sends, and passed through untouched. Every
simulated header carries a ``(demo-simulated)`` comment so nobody mistakes it for a real
verdict, and the message is tagged with ``X-Vouch-Demo``.
"""

from __future__ import annotations

import base64
import hashlib
import secrets
from datetime import UTC, datetime
from email import message_from_bytes, policy
from email.message import EmailMessage
from email.utils import format_datetime, formataddr, make_msgid

from .config import Settings
from .models import AuthSimulation, BuiltMessage, Invoice, SenderIdentity, SendRequest
from .render import Rendered, invoice_lines, render, render_text

DEMO_MARKER = "synthetic invoice generated by demo-tools/invoice-creator; authentication headers simulated"

_SPF_COMMENT = {
    "pass": "sender IP is authorized",
    "fail": "sender IP is not authorized",
    "softfail": "domain discourages use of this IP",
    "none": "no SPF record",
}
_DKIM_COMMENT = {
    "pass": "signature verified",
    "fail": "signature did not verify",
    "softfail": "signature did not verify",
    "none": "no signature",
}
_DMARC_COMMENT = {
    "pass": "p=REJECT",
    "fail": "p=REJECT",
    "softfail": "p=QUARANTINE",
    "none": "no DMARC policy",
}


def auth_results_header(
    authserv_id: str, from_domain: str, auth: AuthSimulation, envelope_domain: str | None = None
) -> str:
    """Authentication-Results value in the shape the backend's parser expects (RFC 8601)."""
    envelope_domain = envelope_domain or from_domain
    dkim_domain = auth.dkim_domain or from_domain
    parts = [f"{authserv_id} (demo-simulated)"]
    parts.append(f"spf={auth.spf} ({_SPF_COMMENT[auth.spf]}) smtp.mailfrom={envelope_domain}")
    if auth.dkim == "none":
        parts.append("dkim=none (no signature)")
    else:
        parts.append(f"dkim={auth.dkim} ({_DKIM_COMMENT[auth.dkim]}) header.d={dkim_domain} header.s=sel1")
    parts.append(f"dmarc={auth.dmarc} ({_DMARC_COMMENT[auth.dmarc]}) header.from={from_domain}")
    return "; ".join(parts)


def received_header(from_domain: str, authserv_id: str, now: datetime) -> str:
    """A synthetic upstream hop. 203.0.113.0/24 is the RFC 5737 documentation range."""
    host = f"mail.{from_domain}" if from_domain else "mail.sender.invalid"
    token = secrets.token_hex(6)
    return (
        f"from {host} ({host} [203.0.113.10]) by {authserv_id} (demo-simulated hop) "
        f"with ESMTPS id {token}; {format_datetime(now)}"
    )


def default_body(inv: Invoice) -> str:
    what = inv.description or "our services"
    return (
        f"Hello,\n\nPlease find attached invoice {inv.invoice_number} for {what}."
        f"\n\nRegards,\n{inv.remit_to.contact_name or inv.vendor_name}"
    )


def auth_summary(sender: SenderIdentity) -> str:
    a = sender.auth
    if not a.enabled:
        return "no Authentication-Results header"
    return f"spf={a.spf} dkim={a.dkim} dmarc={a.dmarc}"


def build_message(
    req: SendRequest, settings: Settings, *, now: datetime | None = None
) -> tuple[EmailMessage, Rendered | None]:
    inv, sender = req.invoice, req.sender
    now = now or datetime.now(UTC)
    from_domain = sender.from_domain or "vouch.local"
    envelope_from = sender.envelope_from or sender.from_addr
    envelope_domain = envelope_from.rsplit("@", 1)[-1].lower() if "@" in envelope_from else from_domain

    msg = EmailMessage(policy=policy.SMTP)
    if sender.add_received_header:
        msg["Received"] = received_header(from_domain, settings.authserv_id, now)
    if sender.auth.enabled:
        msg["Authentication-Results"] = auth_results_header(
            settings.authserv_id, from_domain, sender.auth, envelope_domain
        )
    msg["From"] = formataddr((sender.from_name, sender.from_addr))
    msg["To"] = settings.mail_to
    if sender.reply_to:
        msg["Reply-To"] = sender.reply_to
    msg["Subject"] = sender.subject or f"Invoice {inv.invoice_number}"
    msg["Date"] = format_datetime(now)
    msg["Message-ID"] = make_msgid(domain=from_domain)
    msg["X-Vouch-Demo"] = DEMO_MARKER
    if req.scenario:
        msg["X-Vouch-Demo-Scenario"] = req.scenario

    body = (sender.body or default_body(inv)).strip()
    if req.format == "body":
        body = body + "\n\n" + render_text(inv, settings.owner_name, settings.owner_address)
    msg.set_content(body + "\n")

    attachment = render(inv, req.format, settings.owner_name, settings.owner_address)
    if attachment is not None:
        maintype, subtype = attachment.content_type.split("/", 1)
        msg.add_attachment(attachment.data, maintype=maintype, subtype=subtype, filename=attachment.filename)
    return msg, attachment


def message_bytes(msg: EmailMessage) -> bytes:
    return msg.as_bytes()


def describe(msg: EmailMessage, attachment: Rendered | None, built_id: str, raw: bytes) -> BuiltMessage:
    return BuiltMessage(
        id=built_id,
        message_id=str(msg["Message-ID"] or ""),
        subject=str(msg["Subject"] or ""),
        headers=[[k, str(v)] for k, v in msg.items()],
        body_text=msg.get_body(preferencelist=("plain",)).get_content() if msg.get_body(("plain",)) else "",
        attachment_name=attachment.filename if attachment else None,
        attachment_type=attachment.content_type if attachment else None,
        attachment_size=attachment.size if attachment else 0,
        attachment_sha256=attachment.sha256 if attachment else None,
        eml_size=len(raw),
    )


def eml_to_intake_json(raw: bytes, *, source: str = "email", received_at: datetime | None = None) -> dict:
    """Mirror of the backend's ``parse_eml``: the JSON body ``POST /v1/intake/email`` accepts.

    Headers are kept verbatim (repeated headers joined with newlines, as the backend does);
    attachments are base64 with sha256 and size.
    """
    msg = message_from_bytes(raw, policy=policy.default)
    headers: dict[str, str] = {}
    for key in msg.keys():
        values = [str(v) for v in msg.get_all(key, [])]
        headers[key] = "\n".join(values) if len(values) > 1 else values[0]
    body_text, body_html = "", ""
    attachments: list[dict] = []
    for part in msg.walk():
        if part.is_multipart():
            continue
        disposition = (part.get_content_disposition() or "").lower()
        ctype = part.get_content_type()
        filename = part.get_filename()
        if disposition == "attachment" or (filename and ctype not in ("text/plain", "text/html")):
            payload = part.get_payload(decode=True) or b""
            attachments.append(
                {
                    "filename": filename or "attachment",
                    "content_type": ctype,
                    "data_b64": base64.b64encode(payload).decode(),
                    "sha256": hashlib.sha256(payload).hexdigest(),
                    "size": len(payload),
                }
            )
        elif ctype == "text/plain" and not body_text:
            body_text = part.get_content()
        elif ctype == "text/html" and not body_html:
            body_html = part.get_content()
    return {
        "headers": headers,
        "body_text": body_text,
        "body_html": body_html,
        "attachments": attachments,
        "source": source,
        "received_at": (received_at or datetime.now(UTC)).isoformat().replace("+00:00", "Z"),
    }


